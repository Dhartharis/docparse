DO $EF$
BEGIN
    IF NOT EXISTS(SELECT 1 FROM pg_namespace WHERE nspname = 'access') THEN
        CREATE SCHEMA access;
    END IF;
END $EF$;


CREATE TABLE access."AspNetRoles" (
    "Id" uuid NOT NULL,
    "Name" character varying(256),
    "NormalizedName" character varying(256),
    "ConcurrencyStamp" text,
    CONSTRAINT "PK_AspNetRoles" PRIMARY KEY ("Id")
);


CREATE TABLE access."AspNetUsers" (
    "Id" uuid NOT NULL,
    "UserName" character varying(256),
    "NormalizedUserName" character varying(256),
    "Email" character varying(256),
    "NormalizedEmail" character varying(256),
    "EmailConfirmed" boolean NOT NULL,
    "PasswordHash" text,
    "SecurityStamp" text,
    "ConcurrencyStamp" text,
    "PhoneNumber" text,
    "PhoneNumberConfirmed" boolean NOT NULL,
    "TwoFactorEnabled" boolean NOT NULL,
    "LockoutEnd" timestamp with time zone,
    "LockoutEnabled" boolean NOT NULL,
    "AccessFailedCount" integer NOT NULL,
    CONSTRAINT "PK_AspNetUsers" PRIMARY KEY ("Id")
);


CREATE TABLE access.organizations (
    "Id" uuid NOT NULL,
    "Name" character varying(200) NOT NULL,
    "CreatedAt" timestamp with time zone NOT NULL,
    CONSTRAINT "PK_organizations" PRIMARY KEY ("Id")
);


CREATE TABLE access."AspNetRoleClaims" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "RoleId" uuid NOT NULL,
    "ClaimType" text,
    "ClaimValue" text,
    CONSTRAINT "PK_AspNetRoleClaims" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_AspNetRoleClaims_AspNetRoles_RoleId" FOREIGN KEY ("RoleId") REFERENCES access."AspNetRoles" ("Id") ON DELETE CASCADE
);


CREATE TABLE access."AspNetUserClaims" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "UserId" uuid NOT NULL,
    "ClaimType" text,
    "ClaimValue" text,
    CONSTRAINT "PK_AspNetUserClaims" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_AspNetUserClaims_AspNetUsers_UserId" FOREIGN KEY ("UserId") REFERENCES access."AspNetUsers" ("Id") ON DELETE CASCADE
);


CREATE TABLE access."AspNetUserLogins" (
    "LoginProvider" text NOT NULL,
    "ProviderKey" text NOT NULL,
    "ProviderDisplayName" text,
    "UserId" uuid NOT NULL,
    CONSTRAINT "PK_AspNetUserLogins" PRIMARY KEY ("LoginProvider", "ProviderKey"),
    CONSTRAINT "FK_AspNetUserLogins_AspNetUsers_UserId" FOREIGN KEY ("UserId") REFERENCES access."AspNetUsers" ("Id") ON DELETE CASCADE
);


CREATE TABLE access."AspNetUserRoles" (
    "UserId" uuid NOT NULL,
    "RoleId" uuid NOT NULL,
    CONSTRAINT "PK_AspNetUserRoles" PRIMARY KEY ("UserId", "RoleId"),
    CONSTRAINT "FK_AspNetUserRoles_AspNetRoles_RoleId" FOREIGN KEY ("RoleId") REFERENCES access."AspNetRoles" ("Id") ON DELETE CASCADE,
    CONSTRAINT "FK_AspNetUserRoles_AspNetUsers_UserId" FOREIGN KEY ("UserId") REFERENCES access."AspNetUsers" ("Id") ON DELETE CASCADE
);


CREATE TABLE access."AspNetUserTokens" (
    "UserId" uuid NOT NULL,
    "LoginProvider" text NOT NULL,
    "Name" text NOT NULL,
    "Value" text,
    CONSTRAINT "PK_AspNetUserTokens" PRIMARY KEY ("UserId", "LoginProvider", "Name"),
    CONSTRAINT "FK_AspNetUserTokens_AspNetUsers_UserId" FOREIGN KEY ("UserId") REFERENCES access."AspNetUsers" ("Id") ON DELETE CASCADE
);


CREATE TABLE access.identity_links (
    "Provider" text NOT NULL,
    "Issuer" text NOT NULL,
    "Subject" text NOT NULL,
    "UserId" uuid NOT NULL,
    CONSTRAINT "PK_identity_links" PRIMARY KEY ("Provider", "Issuer", "Subject"),
    CONSTRAINT "FK_identity_links_AspNetUsers_UserId" FOREIGN KEY ("UserId") REFERENCES access."AspNetUsers" ("Id") ON DELETE CASCADE
);


CREATE TABLE access.invitations (
    "Id" uuid NOT NULL,
    "OrganizationId" uuid NOT NULL,
    "Email" text NOT NULL,
    "Role" text NOT NULL,
    "TokenHash" text NOT NULL,
    "ExpiresAt" timestamp with time zone NOT NULL,
    "AcceptedAt" timestamp with time zone,
    CONSTRAINT "PK_invitations" PRIMARY KEY ("Id"),
    CONSTRAINT invitation_role CHECK ("Role" IN ('Admin', 'Viewer')),
    CONSTRAINT "FK_invitations_organizations_OrganizationId" FOREIGN KEY ("OrganizationId") REFERENCES access.organizations ("Id") ON DELETE CASCADE
);


CREATE TABLE access.memberships (
    "OrganizationId" uuid NOT NULL,
    "UserId" uuid NOT NULL,
    "Role" text NOT NULL,
    CONSTRAINT "PK_memberships" PRIMARY KEY ("OrganizationId", "UserId"),
    CONSTRAINT membership_role CHECK ("Role" IN ('Admin', 'Viewer')),
    CONSTRAINT "FK_memberships_AspNetUsers_UserId" FOREIGN KEY ("UserId") REFERENCES access."AspNetUsers" ("Id") ON DELETE CASCADE,
    CONSTRAINT "FK_memberships_organizations_OrganizationId" FOREIGN KEY ("OrganizationId") REFERENCES access.organizations ("Id") ON DELETE CASCADE
);


CREATE INDEX "IX_AspNetRoleClaims_RoleId" ON access."AspNetRoleClaims" ("RoleId");


CREATE UNIQUE INDEX "RoleNameIndex" ON access."AspNetRoles" ("NormalizedName");


CREATE INDEX "IX_AspNetUserClaims_UserId" ON access."AspNetUserClaims" ("UserId");


CREATE INDEX "IX_AspNetUserLogins_UserId" ON access."AspNetUserLogins" ("UserId");


CREATE INDEX "IX_AspNetUserRoles_RoleId" ON access."AspNetUserRoles" ("RoleId");


CREATE INDEX "EmailIndex" ON access."AspNetUsers" ("NormalizedEmail");


CREATE UNIQUE INDEX "UserNameIndex" ON access."AspNetUsers" ("NormalizedUserName");


CREATE INDEX "IX_identity_links_UserId" ON access.identity_links ("UserId");


CREATE UNIQUE INDEX "IX_invitations_OrganizationId_Email" ON access.invitations ("OrganizationId", "Email");


CREATE UNIQUE INDEX "IX_invitations_TokenHash" ON access.invitations ("TokenHash");


CREATE INDEX "IX_memberships_UserId" ON access.memberships ("UserId");


